  getFallbackImageSvg(category = 'General', title = 'OneMarket Item') {
    return 'assets/product-images/placeholder.svg';
  },

  /**
   * Simple modal helper
   */
  openModal({ title, bodyHtml, footerHtml = '', size = 'md' }) {
    let backdrop = document.getElementById('app-modal-backdrop');
    if (!backdrop) {
      backdrop = document.createElement('div');
      backdrop.id = 'app-modal-backdrop';
      backdrop.className = 'modal-backdrop';
      document.body.appendChild(backdrop);
    }

    backdrop.innerHTML = `
      <div class="modal-dialog modal-${size}" role="dialog" aria-modal="true" aria-labelledby="modal-title">
        <div class="modal-header">
          <h2 id="modal-title" class="modal-title">${Utils.escapeHTML(title)}</h2>
          <button class="modal-close-btn" aria-label="Close dialog" id="modal-close-button">
            ${Utils.icons.close}
          </button>
        </div>
        <div class="modal-body">${bodyHtml}</div>
        ${footerHtml ? `<div class="modal-footer">${footerHtml}</div>` : ''}
      </div>
    `;

    backdrop.classList.add('active');
    document.body.classList.add('modal-open');

    const closeHandler = () => Utils.closeModal();
    document.getElementById('modal-close-button').addEventListener('click', closeHandler);
    backdrop.addEventListener('click', (e) => {
      if (e.target === backdrop) closeHandler();
    });

    const escHandler = (e) => {
      if (e.key === 'Escape') {
        closeHandler();
        document.removeEventListener('keydown', escHandler);
      }
    };
    document.addEventListener('keydown', escHandler);
  },

  closeModal() {
    const backdrop = document.getElementById('app-modal-backdrop');
    if (backdrop) {
      backdrop.classList.remove('active');
      document.body.classList.remove('modal-open');
      backdrop.innerHTML = '';
    }
  },

  /**
   * Confirmation dialog helper
   */
  confirmDialog({ title = 'Confirm Action', message, confirmText = 'Confirm', confirmStyle = 'danger', onConfirm }) {
    Utils.openModal({
      title,
      size: 'sm',
      bodyHtml: `<p class="confirm-message">${Utils.escapeHTML(message)}</p>`,
      footerHtml: `
        <button class="btn btn-secondary" onclick="Utils.closeModal()">Cancel</button>
        <button class="btn btn-${confirmStyle}" id="confirm-dialog-btn">${Utils.escapeHTML(confirmText)}</button>
      `
    });

    document.getElementById('confirm-dialog-btn').addEventListener('click', () => {
      Utils.closeModal();
      if (typeof onConfirm === 'function') onConfirm();
    });
  },

